#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
RUNTIME_ROOT_BASE=${RUNTIME_ROOT_BASE:-${ROOT_DIR}/.runtime}

EVAL_CONFIG_PATH=${EVAL_CONFIG_PATH:-${CONFIG_PATH:-${ROOT_DIR}/config/sweagent_infer_ascend_officiallike.yaml}}
SCORE_CONFIG_PATH=${SCORE_CONFIG_PATH:-${ROOT_DIR}/config/sweagent_score_ascend.yaml}
PREPARE_CONFIG_PATH=${PREPARE_CONFIG_PATH:-${ROOT_DIR}/config/sweagent_prepare_ascend.yaml}
MODEL_NAME=${MODEL_NAME:-/path/to/workspace/models/sweagent-7b}
MODEL_PATH=${MODEL_PATH:-${MODEL_NAME}}
API_BASE=${API_BASE:-http://127.0.0.1:8000/v1}

INSTANCE_SLICE=${INSTANCE_SLICE:-:500}
NUM_WORKERS=${NUM_WORKERS:-16}
PREPARE_FIRST=${PREPARE_FIRST:-1}
PREPARE_NUM_WORKERS=${PREPARE_NUM_WORKERS:-${NUM_WORKERS}}
AUTO_START_SERVER=${AUTO_START_SERVER:-0}
POSTPROCESS_DATASET_SIZE=${POSTPROCESS_DATASET_SIZE:-500}
POSTPROCESS_SCORING=${POSTPROCESS_SCORING:-1}
WATCHDOG_ENABLE=${WATCHDOG_ENABLE:-1}
WATCHDOG_STALE_SECONDS=${WATCHDOG_STALE_SECONDS:-1800}
WATCHDOG_POLL_SECONDS=${WATCHDOG_POLL_SECONDS:-60}
WATCHDOG_RECOVERY_GRACE_SECONDS=${WATCHDOG_RECOVERY_GRACE_SECONDS:-180}

EVAL_RUNTIME_ROOT=${EVAL_RUNTIME_ROOT:-${RUNTIME_ROOT_BASE}/ascend-eval-sweagent7b-real-officiallike-formal}
SCORE_RUNTIME_ROOT=${SCORE_RUNTIME_ROOT:-${RUNTIME_ROOT_BASE}/ascend-score-sweagent7b-real-officiallike-formal}
PREDICTIONS_PATH=${PREDICTIONS_PATH:-${EVAL_RUNTIME_ROOT}/output/preds.json}

if [[ ! -f "${EVAL_CONFIG_PATH}" ]]; then
  echo "eval config not found: ${EVAL_CONFIG_PATH}" >&2
  exit 1
fi
if [[ ! -f "${SCORE_CONFIG_PATH}" ]]; then
  echo "score config not found: ${SCORE_CONFIG_PATH}" >&2
  exit 1
fi

mkdir -p "${EVAL_RUNTIME_ROOT}" "${SCORE_RUNTIME_ROOT}"

echo "[formal] eval_root=${EVAL_RUNTIME_ROOT}"
echo "[formal] score_root=${SCORE_RUNTIME_ROOT}"
echo "[formal] eval_config=${EVAL_CONFIG_PATH}"
echo "[formal] score_config=${SCORE_CONFIG_PATH}"
echo "[formal] model=${MODEL_NAME}"
echo "[formal] api_base=${API_BASE}"
echo "[formal] instance_slice=${INSTANCE_SLICE}"
echo "[formal] num_workers=${NUM_WORKERS}"
echo "[formal] prepare_first=${PREPARE_FIRST}"

env   CONFIG_PATH="${EVAL_CONFIG_PATH}"   PREPARE_CONFIG_PATH="${PREPARE_CONFIG_PATH}"   RUNTIME_ROOT="${EVAL_RUNTIME_ROOT}"   API_BASE="${API_BASE}"   MODEL_NAME="${MODEL_NAME}"   MODEL_PATH="${MODEL_PATH}"   INSTANCE_SLICE="${INSTANCE_SLICE}"   NUM_WORKERS="${NUM_WORKERS}"   AUTO_START_SERVER="${AUTO_START_SERVER}"   PREPARE_FIRST="${PREPARE_FIRST}"   PREPARE_NUM_WORKERS="${PREPARE_NUM_WORKERS}"   POSTPROCESS_EVAL=1   POSTPROCESS_DATASET_SIZE="${POSTPROCESS_DATASET_SIZE}"   WATCHDOG_ENABLE="${WATCHDOG_ENABLE}"   WATCHDOG_STALE_SECONDS="${WATCHDOG_STALE_SECONDS}"   WATCHDOG_POLL_SECONDS="${WATCHDOG_POLL_SECONDS}"   WATCHDOG_RECOVERY_GRACE_SECONDS="${WATCHDOG_RECOVERY_GRACE_SECONDS}"   bash "${ROOT_DIR}/sh/run_sweagent_eval_ascend.sh"

if [[ ! -f "${PREDICTIONS_PATH}" ]]; then
  echo "predictions file not found after generation: ${PREDICTIONS_PATH}" >&2
  exit 1
fi

env   CONFIG_PATH="${SCORE_CONFIG_PATH}"   RUNTIME_ROOT="${SCORE_RUNTIME_ROOT}"   PREDICTIONS_PATH="${PREDICTIONS_PATH}"   INSTANCE_SLICE="${INSTANCE_SLICE}"   NUM_WORKERS="${NUM_WORKERS}"   POSTPROCESS_SCORING="${POSTPROCESS_SCORING}"   bash "${ROOT_DIR}/sh/run_swebench_scoring_ascend.sh"
